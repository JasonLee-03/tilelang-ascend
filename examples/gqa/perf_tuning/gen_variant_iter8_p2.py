"""Iter8 P2 variant generator — flat kv1 + flat kv2 with BSND direct-write Output.

Extracts the two SHIPPED flat kernel blocks from examples/gqa/gqa.py
(md5-asserted, line-anchored) and applies the minimal P2 edit — 2 lines per
kernel — so each variant is provably "shipped kernel + tiny diff"
(gen_variants_iter4.py / gen_variant_iter7_p5.py pattern):

    perf_tuning/gqa_flat_bsnd_iter8_variant.py  +  diff_iter8_p2.txt

P2 mechanism (iter6 §7 P2 card; design + probes: p2_bsnd_design_iter8.md):
  * `main`'s Output declaration changes from BHSD [B, N_q, S_padded, D] to
    BSND [B, S_padded, N_q, D].
  * `emit_fin`'s write box changes from `Output[bz, hq0+h, row0:row0+half, :]`
    (contiguous, row stride D) to `Output[bz, row0:row0+half, hq0+h, :]`
    (strided, row stride N_q*D).  Element (b,hq,s,d) lands at
    ((b*S+s)*N_q+hq)*D+d == exactly what _transpose_v1 (transpose_out) wrote
    (algebraic identity, M=N_q/N=S/R=D) and exactly what the decode
    dense_expert BSND precedent declares (gqa.py:1118/1450).
  * NOTHING else changes: arithmetic (emit_sm/ao/fin op order), flags/SEMs,
    tokens, slots, ws geometry, C side, task_range/_ids, UB/L1/L0 allocation.
    The generated code is byte-identical to shipped outside those 2 lines
    per kernel (audited below), so outputs must be BIT-IDENTICAL after the
    host skips transpose_out (Gate 0 criterion).
  * Coverage gate (host side, applied by the harness/integration, NOT by the
    kernel): S % 64 == 0 so S_padded == S and the row window never leaves the
    real-S range => no crop, no masked writes (design §3.4).

Run:  python3 examples/gqa/perf_tuning/gen_variant_iter8_p2.py
"""

import difflib
import hashlib
import os

HERE = os.path.dirname(os.path.abspath(__file__))
GQA_DIR = os.path.dirname(HERE)
GQA_PY = os.path.join(GQA_DIR, "gqa.py")

EXPECT_MD5 = "4b4e453e4b8f2922baefbecb85912494"

# 1-based inclusive line ranges of the shipped factory blocks
BLOCKS = {
    "kv1": (2981, 3439, "_gqa_kernel_prefill_g2stack_flat"),
    "kv2": (3456, 4027, "_gqa_kernel_prefill_g2stack_flat_kv2"),
}

# pinned edit sites (absolute gqa.py line numbers)
EDITS = {
    "kv1": {
        "decl": 3280,
        "write": 3270,
    },
    "kv2": {
        "decl": 3804,
        "write": 3794,
    },
}

DECL_OLD = "        Output: T.Tensor([B, N_q, S_padded, D], dtype),  # type: ignore  BHSD\n"
DECL_NEW = (
    "        # [S3-iter8-P2] BSND direct write: the FIN box below is strided\n"
    "        # (row stride N_q*D) instead of contiguous, so the host skips\n"
    "        # transpose_out entirely (design: perf_tuning/p2_bsnd_design_iter8.md).\n"
    "        Output: T.Tensor([B, S_padded, N_q, D], dtype),  # type: ignore  BSND\n"
)
WRITE_OLD = "                Output[bz, hq0 + h, bx * block_M + vid * half : bx * block_M + vid * half + half, :],\n"
WRITE_NEW = (
    "                # [S3-iter8-P2] BSND box (bz, rows, hq, :) — same element set,\n"
    "                # strided rows; one DataCopyPad, instruction count unchanged.\n"
    "                Output[bz, bx * block_M + vid * half : bx * block_M + vid * half + half, hq0 + h, :],\n"
)

HEADER = '''"""P2 variant — flat kv1 / flat kv2 with BSND direct-write Output.

Standalone Gate-0/Gate-2 development file (Stage 3 iter8).  Generated by
gen_variant_iter8_p2.py from the SHIPPED
`_gqa_kernel_prefill_g2stack_flat` (gqa.py:2981-3439) and
`_gqa_kernel_prefill_g2stack_flat_kv2` (gqa.py:3456-4027) blocks of
examples/gqa/gqa.py (md5 4b4e453e4b8f2922baefbecb85912494) via 2 line-scoped
edits per kernel — see diff_iter8_p2.txt in this directory for the complete
unified diff (the audit artifact).  gqa.py is NOT modified by this file;
constants are imported read-only.

Mechanism (iter6 roofline §7 P2 / §6.3-4 "absorbable by main"; design and
probe evidence: perf_tuning/p2_bsnd_design_iter8.md):
  Output declared BSND [B, S_padded, N_q, D] and the FIN write box becomes
  `Output[bz, row0:row0+half, hq0+h, :]` — a strided MTE3 box (row stride
  N_q*D, 32 x 256B bursts) carrying exactly the element set that
  transpose_out's `_transpose_v1` used to move, so the host can skip the
  transpose_out launch altogether on the covered domain (aligned S:
  S_padded == S, no crop, no masked rows).

Arithmetic is UNTOUCHED (emit_sm / emit_ao / emit_fin op order and values
identical; only the GM destination addressing of the last copy changes), the
flag/semaphore protocol is UNTOUCHED (every set/wait line byte-identical —
audited), and the UB/L1/L0/ws geometry is UNTOUCHED => final outputs must be
BIT-IDENTICAL to the shipped main+transpose_out chain (Gate 0 criterion;
special values: NaN positions equal, Inf positions+signs equal, finite bits
equal — verified with the iter5 injection set).

Probe evidence backing the form choice (perf_tuning/probe_iter8_P2_bsnd.py):
  * 15/15 bit-exact address mapping (5 shapes x bhsd/bsnd4d/bsnd2d)
  * generated code = ONE copy_ub_to_gm/DataCopyPad, instruction count equal
    to the contiguous arm; only dstStride differs
  * strided MTE3 time per box = 1.07-1.17x contiguous => predicted main
    kernel increment +0.13..+0.98us vs the 7.67-29.58us tout eliminated
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import tilelang
from tilelang import language as T
from tilelang.intrinsics import make_zn_layout, make_nz_layout

from gqa import P28_EXPERT_PASS_CONFIGS, P28_NUM_CORES, _BIG_NEG  # noqa: E402,F401


'''


def load_blocks():
    md5 = hashlib.md5(open(GQA_PY, "rb").read()).hexdigest()
    assert md5 == EXPECT_MD5, f"gqa.py drifted: md5 {md5} != {EXPECT_MD5}"
    lines = open(GQA_PY).read().splitlines(keepends=True)
    out = {}
    for tag, (start, end, fname) in BLOCKS.items():
        block = lines[start - 1 : end]
        # boundary assertions (fail loudly on drift)
        assert block[0].startswith("@tilelang.jit(out_idx=[4], workspace_idx=[5, 6, 7]"), block[0]
        assert block[1].startswith(f"def {fname}("), block[1]
        assert block[-1].rstrip() == "    return main", block[-1]
        # edit-site pins
        d = EDITS[tag]["decl"] - start
        w = EDITS[tag]["write"] - start
        assert block[d] == DECL_OLD, f"{tag} decl site drifted:\n{block[d]!r}"
        assert block[w] == WRITE_OLD, f"{tag} write site drifted:\n{block[w]!r}"
        # uniqueness of the pinned patterns inside the block
        whole = "".join(block)
        assert whole.count(DECL_OLD) == 1, f"{tag}: {whole.count(DECL_OLD)} decl sites"
        assert whole.count(WRITE_OLD) == 1, f"{tag}: {whole.count(WRITE_OLD)} write sites"
        out[tag] = block
    return out


def make_p2(block, tag):
    lines = list(block)
    start = BLOCKS[tag][0]
    d = EDITS[tag]["decl"] - start
    w = EDITS[tag]["write"] - start
    lines[d] = DECL_NEW
    lines[w] = WRITE_NEW
    return lines


def audit(variant_lines, block, tag):
    """Static re-audit: the variant differs from shipped in EXACTLY the 2 pinned sites."""
    text = "".join(variant_lines)
    ship = "".join(block)

    # (1) the two edits landed
    assert text.count("Output: T.Tensor([B, S_padded, N_q, D], dtype)") == 1, "decl edit missing"
    assert "Output: T.Tensor([B, N_q, S_padded, D], dtype)" not in text, "old BHSD decl survives"
    assert text.count("Output[bz, bx * block_M + vid * half : bx * block_M + vid * half + half, hq0 + h, :],") == 1, "write edit missing"
    assert "Output[bz, hq0 + h, bx * block_M" not in text, "old BHSD write survives"

    # (2) flag protocol byte-identical (pacing invariance, design §4)
    def flaglines(s):
        return [ln for ln in s.splitlines()
                if any(k in ln for k in ("set_flag", "wait_flag", "set_cross_flag", "wait_cross_flag"))]

    assert flaglines(ship) == flaglines(text), "flag protocol lines diverged"
    for k in ("SEM_WS1_C2V", "SEM_WS1_V2C", "SEM_WS2_V2C", "SEM_WS2_C2V", "SEM_WS3_C2V", "SEM_WS3_V2C",
              "SIG_K_L1", "SIG_V_L1", "SIG_P_L1", "SIG_Q_L1", "SIG_L0AB", "SIG_L0C", "SIG_IO_UB",
              "SIG_MASK", "SIG_S_HALF"):
        assert ship.count(k + " = ") == text.count(k + " = "), k

    # (3) memory geometry identical (UB liveness, design §5)
    for pat in ("T.alloc_ub(", "T.alloc_L1(", "T.alloc_L0A(", "T.alloc_L0B(", "T.alloc_L0C(",
                "ws_s: T.Tensor", "ws_p: T.Tensor", "ws_o: T.Tensor",
                "Q: T.Tensor", "K: T.Tensor", "V: T.Tensor", "Mask: T.Tensor",
                "make_zn_layout", "make_nz_layout", "T.annotate_layout"):
        assert ship.count(pat) == text.count(pat), pat

    # (4) arithmetic untouched: the ONLY code-line change is the FIN write
    # destination.  Verified structurally from the diff itself (both edit sites
    # are multi-line T.copy / signature spans, so a keyword filter is not
    # sufficient): every removed line must be one of the 2 pinned originals and
    # every added line must be a comment or one of the 2 pinned replacements.
    diff = list(difflib.unified_diff(ship.splitlines(), text.splitlines(), lineterm=""))
    removed = [ln[1:] + "\n" for ln in diff if ln.startswith("-") and not ln.startswith("---")]
    added = [ln[1:] + "\n" for ln in diff if ln.startswith("+") and not ln.startswith("+++")]
    assert removed == [WRITE_OLD, DECL_OLD], f"unexpected removed lines: {removed}"
    exp_added = [ln + "\n" for ln in WRITE_NEW.split("\n") if ln] + \
                [ln + "\n" for ln in DECL_NEW.split("\n") if ln]
    assert added == exp_added, f"unexpected added lines:\n{added}\nvs\n{exp_added}"
    for ln in added:
        assert ln.lstrip().startswith("#") or ln in (WRITE_NEW, DECL_NEW) or \
            ln.strip() in DECL_NEW or ln.strip() in WRITE_NEW, f"non-comment addition: {ln!r}"
    # code-only projection (comments stripped) must differ in exactly 2 lines
    def code_only(s):
        out = []
        for ln in s.splitlines():
            st = ln.strip()
            if not st or st.startswith("#"):
                continue
            out.append(ln)
        return out

    cs, cv = code_only(ship), code_only(text)
    assert len(cs) == len(cv), f"code line count {len(cs)} != {len(cv)}"
    changed = [(a, b) for a, b in zip(cs, cv) if a != b]
    assert len(changed) == 2, f"expected 2 changed code lines, got {changed}"
    def last_code(s):
        return [ln for ln in s.split("\n") if ln.strip() and not ln.strip().startswith("#")][-1].strip()

    assert changed[0][0].strip() == WRITE_OLD.strip(), changed[0][0]
    assert changed[0][1].strip() == last_code(WRITE_NEW), changed[0][1]
    assert changed[1][0].strip() == DECL_OLD.strip(), changed[1][0]
    assert changed[1][1].strip() == last_code(DECL_NEW), changed[1][1]

    # (5) task decomposition / schedule untouched
    for pat in ("def task_range", "def _ids", "T.serial(my_count", "emit_qload(", "emit_g1(",
                "emit_g2(", "emit_sm(", "emit_ao(", "emit_fin("):
        assert ship.count(pat) == text.count(pat), pat

    # (6) diff hunk census: exactly 2 hunks (decl + write)
    diff = list(difflib.unified_diff(ship.splitlines(), text.splitlines(), lineterm=""))
    hunks = [ln for ln in diff if ln.startswith("@@")]
    assert len(hunks) == 2, f"unexpected diff spread ({len(hunks)} hunks): {hunks}"
    return diff


def main():
    blocks = load_blocks()
    all_diff = []
    parts = []
    for tag in ("kv1", "kv2"):
        variant = make_p2(blocks[tag], tag)
        diff = audit(variant, blocks[tag], tag)
        all_diff.append(f"### {tag} — {BLOCKS[tag][2]} (gqa.py:{BLOCKS[tag][0]}-{BLOCKS[tag][1]})")
        all_diff.extend(diff)
        all_diff.append("")
        parts.append("".join(variant))
        print(f"[{tag}] audit OK: 2 edits, flag lines identical, op lines identical except the "
              f"FIN destination, memory geometry identical, 2 diff hunks")
    dst = os.path.join(HERE, "gqa_flat_bsnd_iter8_variant.py")
    with open(dst, "w") as f:
        f.write(HEADER)
        f.write("\n\n".join(parts))
    with open(os.path.join(HERE, "diff_iter8_p2.txt"), "w") as f:
        f.write("\n".join(all_diff) + "\n")
    import ast

    ast.parse(open(dst).read())
    print(f"WROTE {dst}")
    print(f"WROTE {os.path.join(HERE, 'diff_iter8_p2.txt')} ({len(all_diff)} lines)")


if __name__ == "__main__":
    main()

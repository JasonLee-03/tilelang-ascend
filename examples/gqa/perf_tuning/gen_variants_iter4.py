"""Iter4 variant generator — C1 (ns_flat=4) and C3 (G2-first C step).

Extracts the shipped `_gqa_kernel_prefill_g2stack_flat` block from
examples/gqa/gqa.py (lines verified by assertion) and applies MINIMAL
line-scoped edits, so each variant is provably "shipped kernel + small diff".
The unified diffs are written next to the variants for audit:

    perf_tuning/gqa_flat_ns4_variant.py       (C1)  + diff_iter4_ns4.txt
    perf_tuning/gqa_flat_g2first_variant.py   (C3)  + diff_iter4_g2first.txt

C1 mechanism (see perf_log iter4 / candidate_iter4_C1.json for the full
derivation):
  * ws_s/ws_p/ws_o GM ring slots: x % 2 -> x % 4 (second tensor dim 2 -> 4).
  * l0a/l0b/l0c parity (x%2), k/v L1 slots (x%2), q_l1 single slot, V-side
    UB task-parity state slots (par = x%2), per-u set/wait EVENT COUNTS and
    their pipe attribution: ALL UNCHANGED.
  * Init pre-set tokens of the three RELEASE semaphores (WS1_V2C, WS2_C2V,
    WS3_V2C): 1 -> 4.  This is the load-bearing change: the semaphores are
    single counting ids (0-5), so with 1 token the k-th wait strictly consumes
    the k-th set (FIFO), pinning SM(x) <- G2(x-1), G1(x) <- SM(x-1),
    G2(x) <- AO(x-1) REGARDLESS of slot count.  With ns_flat tokens the first
    ns_flat writes per ring are ungated (fresh slots) and in steady state the
    release gates become slot-exact: SM(x) <- G2(x-4), G1(x) <- SM(x-4),
    G2(x) <- AO(x-4)  => the 2-slot round-trip coupling (iter3 V-id3
    1.67-2.06us/u + C-id1 1.76-2.81us/u) is broken; steady period bounded by
    the V-side pacer throughput instead.
  * Max pending depth per cross id ~ ns_flat + 1 = 5 <= 6 (iter2 safety
    bound; hardware limit 15) — derivation in the report.

C3 mechanism: steady C step `G1(t+1) -> G2(t) -> Qload(t+2)` becomes
`G2(t) -> G1(t+1) -> Qload(t+2)`.  G2(t)'s ws_p MTE2 read (and its
WS2_C2V / WS3_C2V sets) fire at the HEAD of the C step instead of after
G1(t+1)'s ~2.8us id1 blocking wait + full K/V load/mma/FIX — directly
attacking V-id3.  Slot ownership untouched: G2(t) uses l0*[t%2] / v_l1[t%2],
G1(t+1) uses l0*[(t+1)%2] / k_l1,v_l1[(t+1)%2] — disjoint parity, local
flags unchanged, set/wait counts unchanged.  Cost side: ws_s(t+1) FIX write
lands later by ~dur(G2(t)) -> V-id0 / C-id1 may rise (feedback loop;
sign unpredictable on paper — measured).

Run:  python3 examples/gqa/perf_tuning/gen_variants_iter4.py
"""


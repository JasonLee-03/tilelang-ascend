def make_g2first(block):
    lines = list(block)
    lm = {BLOCK_START + i: i for i in range(len(block))}

    # steady-step comment (line 3360) + body reorder (3362/3363)
    assert "G1(t+1) -> G2(t) -> Qload(t+2)" in lines[lm[3360]]
    lines[lm[3360]] = "                #      [C3] G2(t) -> G1(t+1) -> Qload(t+2) ----\n"
    g1_line = lines[lm[3362]]
    g2_line = lines[lm[3363]]
    assert "emit_g1(t + 1," in g1_line and "emit_g2(t," in g2_line
    lines[lm[3362]] = g2_line.rstrip("\n") + "  # [C3] head of step\n"
    lines[lm[3363]] = g1_line
    return lines



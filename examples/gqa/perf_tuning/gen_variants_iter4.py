def write_variant(fname, header, block_lines, diffname, orig):
    path = os.path.join(HERE, fname)
    with open(path, "w") as f:
        f.write(header)
        f.writelines(block_lines)
    diff = list(
        difflib.unified_diff(
            orig, block_lines,
            fromfile="gqa.py[2981:3423] (shipped flat kernel)",
            tofile=fname,
            n=3,
        )
    )
    with open(os.path.join(HERE, diffname), "w") as f:
        f.writelines(diff)
    n_hunks = sum(1 for d in diff if d.startswith("@@"))
    n_plus = sum(1 for d in diff if d.startswith("+") and not d.startswith("+++"))
    n_minus = sum(1 for d in diff if d.startswith("-") and not d.startswith("---"))
    print(f"{fname}: +{n_plus}/-{n_minus} lines in {n_hunks} hunks -> {diffname}")



def load_block():
    import hashlib

    md5 = hashlib.md5(open(GQA_PY, "rb").read()).hexdigest()
    assert md5 == EXPECT_MD5, f"gqa.py drifted: md5 {md5} != {EXPECT_MD5}"
    lines = open(GQA_PY).read().splitlines(keepends=True)
    block = lines[BLOCK_START - 1 : BLOCK_END]
    # boundary assertions (fail loudly if gqa.py drifted)
    assert block[0].startswith("@tilelang.jit(out_idx=[4], workspace_idx=[5, 6, 7]"), block[0]
    assert block[1].startswith("def _gqa_kernel_prefill_g2stack_flat_kv2("), block[1]
    assert block[-1].rstrip() == "    return main", block[-1]
    # edit-site context assertions
    assert block[IDX_FILL].rstrip() == "            T.tile.fill(neg_sm, neg_sm_cap)", block[IDX_FILL]
    assert block[IDX_FILL - 1].rstrip() == "        if first_kv:", block[IDX_FILL - 1]
    assert block[IDX_INIT_FILL].rstrip() == "                T.tile.fill(neg_sm, neg_sm_cap)", block[IDX_INIT_FILL]
    assert "State written: neg_sm[h*2+kvpar]" in block[IDX_DOCSTR], block[IDX_DOCSTR]
    assert block[IDX_ALLOC_CMT].rstrip().endswith("# idx h*2 + cur (g2stack semantics)"), block[IDX_ALLOC_CMT]
    for idx, n in CUR_COUNTS.items():
        assert block[idx].count(CUR_PAT) == n, (idx, block[idx])
    for idx, n in PRV_COUNTS.items():
        assert block[idx].count(PRV_PAT) == n, (idx, block[idx])
    whole = "".join(block)
    assert whole.count("T.tile.fill(neg_sm, neg_sm_cap)") == 2
    assert whole.count(CUR_PAT) == sum(CUR_COUNTS.values()) == 7
    assert whole.count(PRV_PAT) == sum(PRV_COUNTS.values()) == 2

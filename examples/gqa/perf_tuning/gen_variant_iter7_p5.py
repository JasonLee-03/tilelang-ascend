def audit(variant_lines, block):
    """Static re-audit of the generated variant (post-write, pre-NPU)."""
    text = "".join(variant_lines)
    ship = "".join(block)
    # remap completeness
    assert text.count(CUR_NEW) == 7, text.count(CUR_NEW)
    assert text.count(PRV_NEW) == 2, text.count(PRV_NEW)
    assert CUR_PAT not in text and PRV_PAT not in text, "un-remapped legacy slot index"
    # fills: one-shot init whole-buffer KEPT; per-task refill narrowed
    assert text.count("T.tile.fill(neg_sm, neg_sm_cap)") == 1, "init fill must survive"
    assert text.count("T.tile.fill(neg_sm[(1 - kvpar) * 2 : (1 - kvpar) * 2 + 2, :, :], neg_sm_cap)") == 1
    # acc_o/sumexp per-task fills untouched (NaN discipline)
    assert text.count("T.tile.fill(acc_o[tpar * 2 + h, :, :], 0.0)") == ship.count(
        "T.tile.fill(acc_o[tpar * 2 + h, :, :], 0.0)")
    assert text.count("T.tile.fill(sumexp[tpar * 2 + h, :, :], 0.0)") == ship.count(
        "T.tile.fill(sumexp[tpar * 2 + h, :, :], 0.0)")
    # flag protocol untouched: every set/wait line identical to shipped
    flag_ship = [ln for ln in ship.splitlines() if "set_flag" in ln or "wait_flag" in ln
                 or "set_cross_flag" in ln or "wait_cross_flag" in ln]
    flag_var = [ln for ln in text.splitlines() if "set_flag" in ln or "wait_flag" in ln
                or "set_cross_flag" in ln or "wait_cross_flag" in ln]
    assert flag_ship == flag_var, "flag protocol lines diverged"
    # ws/L0/L1 geometry untouched
    for pat in ["ws_s = ", "ws_p = ", "ws_o = ", "T.alloc_l1", "T.alloc_l0a", "T.alloc_l0b",
                "T.alloc_l0c", "alloc_ub([4, half, 1]"]:
        assert text.count(pat) == ship.count(pat), pat
    # diff hunk census: only the pinned regions may differ
    diff = list(difflib.unified_diff(ship.splitlines(), text.splitlines(), lineterm=""))
    hunks = [ln for ln in diff if ln.startswith("@@")]
    assert len(hunks) <= 4, f"unexpected diff spread: {hunks}"
    return diff


